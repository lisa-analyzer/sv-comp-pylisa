# Standard library imports
from dataclasses import dataclass

# Project-local imports
from cli.models.lisa_report.fields.info import Info
from cli.models.lisa_report.fields.notice import Notice
from cli.models.lisa_report.fields.warning import Warning


@dataclass
class LisaReport:
    """
    Represents the 'report' JSON file generated by LiSA
    """

    # There are other fields (files, configuration, etc.) in the report. Add them up upon the need
    warnings: list[Warning]
    notices: list[Notice]
    info: Info

    def __init__(self, warnings, notices, info, **_):
        self.warnings = [Warning(**w) if isinstance(w, dict) else w for w in warnings]
        self.notices = [Notice(**n) if isinstance(n, dict) else n for n in notices]
        self.info = Info(**info)

    def has_warnings(self) -> bool:
        return self.info.warnings > 0

    def has_notices(self) -> bool:
        return self.info.notices > 0

    def list_warnings(self) -> list[str]:
        return [w.extract_warning() for w in self.warnings]

    def list_notices(self) -> list[str]:
        return [n.extract_notice() for n in self.notices]

    # assertion safety specific

    def list_assertion_safety_warnings(self) -> list[Warning]:
        return [w for w in self.warnings if w.is_assertion_safety_warning()]

    def has_assertion_safety_warnings(self) -> bool:
        return len(self.list_assertion_safety_warnings()) > 0

    def has_only_possible_assertion_safety_warnings(self) -> bool:
        return all(
            warning.is_possible_warning()
            for warning in self.list_assertion_safety_warnings()
        )

    def has_possible_assertion_safety_warning(self) -> bool:
        return any(
            warning.is_possible_warning()
            for warning in self.list_assertion_safety_warnings()
        )

    def has_only_definite_assertion_safety_warnings(self) -> bool:
        return all(
            not warning.is_possible_warning()
            for warning in self.list_assertion_safety_warnings()
        )

    def has_definite_assertion_safety_warning(self) -> bool:
        return any(
            not warning.is_possible_warning()
            for warning in self.list_assertion_safety_warnings()
        )

